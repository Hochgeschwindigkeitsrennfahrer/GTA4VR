#include <cstdio>
#include <cstdlib>
#include <string>
#include <thread>
#include "../../source/includes/vrconstantprobe.hpp"
import vrprofile;

void Check(bool ok,const char* message)
{if(!ok) {std::fprintf(stderr,"Profile test failed: %s\n",message); std::exit(1);}}
int main()
{
    using namespace VRProfile;
    VRConstantProbe::Observer constants;
    float block[8]{1,2,3,4,5,6,7,8};
    Check(!constants.Observe(10,block,2),"unknown constants are not duplicates");
    Check(constants.Observe(10,block,2),"identical register range");
    Check(constants.Observe(11,block+4,1),"overlapping known range");
    constants.Invalidate(11);
    Check(!constants.Observe(10,block,2),"override invalidates duplicate candidate");
    Check(!constants.Observe(255,block,2) && !constants.Observe(0,nullptr,1),"bounded observer");
    block[0]=0.0f; constants.Observe(10,block,1);
    block[0]=-0.0f;
    Check(!constants.Observe(10,block,1),"compare exact float bytes including signed zero");
    constants.Reset();
    Check(!constants.Observe(10,block,1),"phase reset invalidates shadow");
    Check(Begin().epoch==0,"inactive fast path");
    Check(!ConstantObservationEnabled(),"constant observer inactive");
    Command("profile-start-cpu-constants");
    Check(ConstantObservationEnabled() && !GPUQueriesEnabled(),"explicit CPU constant observer");
    Command("profile-stop");
    Check(!ConstantObservationEnabled(),"stop disables observer");
    Command("profile-start-cpu");
    Check(!ConstantObservationEnabled(),"ordinary capture disables observer");
    Check(!DrawObservationEnabled(),"draw observer disabled in ordinary capture");
    Command("profile-start-cpu-broadvisibility");
    Check(BroadVisibilityEnabled() && !TextureLinearEnabled() && !DrawObservationEnabled() && !StateObservationEnabled() && !GPUQueriesEnabled(),"isolated visibility test");
    Command("profile-stop"); Check(!BroadVisibilityEnabled(),"stop clears visibility test");
    Command("profile-start-cpu"); Check(!BroadVisibilityEnabled(),"ordinary capture restores exact eye visibility");
    Command("profile-start-cpu-texturelinear");
    Check(TextureLinearEnabled() && !DrawForwardingEnabled() && !DrawObservationEnabled() && !ConstantObservationEnabled() && !StateObservationEnabled() && !GPUQueriesEnabled(),"linear texture control has no heavy observers");
    Command("profile-stop"); Check(!TextureLinearEnabled(),"stop disables linear texture control");
    Command("profile-start-cpu"); Check(!TextureLinearEnabled(),"ordinary restart clears linear texture control");
    Command("profile-start-cpu-drawforwarding");
    Check(DrawForwardingEnabled() && !DrawObservationEnabled() && !ConstantObservationEnabled() && !StateObservationEnabled() && !GPUQueriesEnabled(),"forwarding control has no heavy observers");
    Command("profile-stop"); Check(!DrawForwardingEnabled(),"stop disables forwarding control");
    Command("profile-start-cpu"); Check(!DrawForwardingEnabled(),"ordinary restart clears forwarding control");
    Command("profile-start-cpu-draws");
    const auto drawEpoch=Begin().epoch;
    Check(DrawObservationEnabled() && !GPUQueriesEnabled() && !ConstantObservationEnabled(),"isolated sparse draw mode");
    DrawCounters drawBatch{64,60,128,256,1,1,.02,.02};
    DrawCalls(0,1,drawEpoch,drawBatch);
    DrawCalls(1,3,drawEpoch,drawBatch);
    DrawCalls(2,1,drawEpoch,drawBatch); DrawCalls(0,4,drawEpoch,drawBatch);
    auto invalidBatch=drawBatch; invalidBatch.timedCalls=65;
    DrawCalls(0,1,drawEpoch,invalidBatch);
    const auto drawResult=Command("profile-draws 0 1");
    Check(drawResult.find("\"streams\":1,\"calls\":64,\"indexedCalls\":60")!=std::string::npos,"draw counters validate bounds and aggregate once");
    Check(drawResult.find("\"sampledMeanDeviceUs\":20.000000")!=std::string::npos,"sampled units remain microseconds, not whole stream time");
    Check(drawResult.size()<768,"paged draw result fits bridge response");
    Check(Command("profile-draws 0 4").find("\"ok\":false")!=std::string::npos,"invalid phase rejected");
    Check(Command("profile-draws 0 1 extra").find("\"ok\":false")!=std::string::npos,"trailing command rejected");
    Command("profile-start-cpu-draws");
    DrawCalls(0,1,drawEpoch,drawBatch);
    Check(Command("profile-draws 0 1").find("\"calls\":0")!=std::string::npos,"restart rejects stale draw batch");
    Command("profile-stop"); Check(!DrawObservationEnabled(),"stop disables draw observation");
    Command("profile-start-cpu"); Check(!DrawObservationEnabled(),"ordinary restart clears draw mode");
    DrawCalls(0,1,Begin().epoch,drawBatch);
    Check(Command("profile-draws 0 1").find("\"calls\":0")!=std::string::npos,"ordinary capture cannot publish draw observer data");
    Check(!DisableAmbientOcclusion(),"AO enabled outside diagnostic");
    Check(!StateObservationEnabled(),"state observer off in ordinary capture");
    Command("profile-start-cpu-states");
    const auto stateEpoch=Begin().epoch;
    Check(StateObservationEnabled() && !DrawObservationEnabled() && !ConstantObservationEnabled() && !GPUQueriesEnabled(),"isolated state observer mode");
    StateCounters stateBatch{128,1,2,.04,.03};
    StateCalls(0,StateKind::Texture,stateEpoch,stateBatch);
    StateCalls(2,StateKind::Texture,stateEpoch,stateBatch);
    StateCalls(0,StateKind::Count,stateEpoch,stateBatch);
    auto invalidState=stateBatch; invalidState.failedCalls=129;
    StateCalls(0,StateKind::Texture,stateEpoch,invalidState);
    const auto stateResult=Command("profile-states 0 0");
    Check(stateResult.find("\"streams\":1,\"calls\":128")!=std::string::npos,"state bounds and publication");
    Check(stateResult.find("\"sampledMeanDeviceUs\":20.000000")!=std::string::npos,"state sampled units");
    Check(stateResult.size()<640,"state result fits bridge");
    Check(Command("profile-states 0 10").find("\"ok\":false")!=std::string::npos,"invalid state kind rejected");
    Check(Command("profile-states 0 0 extra").find("\"ok\":false")!=std::string::npos,"trailing state argument rejected");
    Command("profile-start-cpu-states");
    StateCalls(0,StateKind::Texture,stateEpoch,stateBatch);
    Check(Command("profile-states 0 0").find("\"calls\":0")!=std::string::npos,"stale state epoch discarded");
    Command("profile-stop"); Check(!StateObservationEnabled(),"stop disables state observation");
    Command("profile-start-cpu"); Check(!StateObservationEnabled(),"ordinary start resets state mode");
    StateCalls(0,StateKind::Texture,Begin().epoch,stateBatch);
    Check(Command("profile-states 0 0").find("\"calls\":0")!=std::string::npos,"ordinary mode rejects state publication");
    Command("profile-start-cpu-noao");
    Check(DisableAmbientOcclusion() && !GPUQueriesEnabled(),"bounded AO isolation enabled");
    Command("profile-stop");
    Check(!DisableAmbientOcclusion(),"stop restores AO");
    Command("profile-start-cpu");
    Check(!DisableAmbientOcclusion(),"ordinary capture clears AO isolation");
    Command("profile-start-cpu-noflush");
    Check(NonflushingPoll() && !GPUQueriesEnabled(),"bounded poll experiment enabled");
    Command("profile-stop");
    Check(!NonflushingPoll(),"stop restores original polling behavior");
    Command("profile-start-cpu");
    Check(!NonflushingPoll(),"ordinary CPU capture clears poll experiment");
    Check(!GPUQueriesEnabled(),"CPU-only capture disables GPU query insertion");
    Check(Command("profile-status").find("\"gpuQueries\":false")!=std::string::npos,"mode is recorded");
    Command("profile-start");
    Check(GPUQueriesEnabled(),"ordinary capture restores GPU queries");
    const auto stale=Begin();
    Command("profile-start");
    const auto current=Begin();
    ConstantWrites(0,true,stale.epoch,99,99,99);
    ConstantWrites(0,true,current.epoch,10,20,3);
    ConstantWrites(1,false,current.epoch,4,8,1);
    Check(Command("profile-constants").find("\"calls\":10,\"vectors\":20,\"repeatedCandidates\":3")!=std::string::npos,"aggregate current counters, discard stale epoch");
    BeforeXRWait();
    Check(Command("profile-metric renderBeforeXRWait").find("\"samples\":0")!=std::string::npos,"no boundary without an eye stream");
    EyeExecutionStarted();
    std::thread otherBoundary([] {BeforeXRWait();}); otherBoundary.join();
    Check(Command("profile-metric renderBeforeXRWait").find("\"samples\":0")!=std::string::npos,"boundary stays on the owning render thread");
    BeforeXRWait(); BeforeXRWait();
    Check(Command("profile-metric renderBeforeXRWait").find("\"samples\":1")!=std::string::npos,"consume each eye boundary once");
    Total oldTotal{stale.epoch,17};
    Flush(Metric::Eye0Routing,oldTotal);
    Check(Command("profile-metric eye0Routing").find("\"samples\":0")!=std::string::npos,"discard old aggregate");
    Total total{current.epoch,17};
    Flush(Metric::Eye0Routing,total);
    Check(Command("profile-metric eye0Routing").find("\"meanMs\":17.0000")!=std::string::npos,"publish aggregate once");
    Flush(Metric::Eye0Routing,total);
    Check(Command("profile-metric eye0Routing").find("\"samples\":1")!=std::string::npos,"cleared aggregate cannot duplicate");
    Check(current.epoch!=stale.epoch,"restart generation");
    End(Metric::ProcessStub,stale);
    Check(Command("profile-metric processStub").find("\"samples\":0")!=std::string::npos,"discard old span");
    for(unsigned i=1;i<=100;++i) Record(Metric::ProcessStub,current.epoch,i);
    const auto summary=Command("profile-metric processStub");
    Check(summary.find("\"medianMs\":50.0000")!=std::string::npos,"median");
    Check(summary.find("\"p95Ms\":95.0000")!=std::string::npos,"p95");
    Check(summary.find("\"p99Ms\":99.0000")!=std::string::npos,"p99");
    Check(summary.find("\"over11_11ms\":89")!=std::string::npos,"budget count");
    auto writer=[&] {for(unsigned i=0;i<5000;++i) Record(Metric::Visibility,current.epoch,1);};
    std::thread a(writer),b(writer); a.join(); b.join();
    const auto bounded=Command("profile-metric visibility");
    Check(bounded.find("\"samples\":8192")!=std::string::npos,"capacity");
    Check(bounded.find("\"dropped\":1808")!=std::string::npos,"concurrent overflow count");
    Command("profile-stop");
    Record(Metric::ProcessStub,current.epoch,10000);
    Check(Command("profile-metric processStub").find("\"samples\":100")!=std::string::npos,"stop freezes data");
    Check(Begin().epoch==0,"stopped fast path");
    EyeExecutionStarted();
    Command("profile-start-cpu");
    BeforeXRWait();
    Check(Command("profile-metric renderBeforeXRWait").find("\"samples\":0")!=std::string::npos,"inactive eye boundary cannot leak into a new capture");
    EyeExecutionStarted();
    Command("profile-start-cpu");
    BeforeXRWait();
    Check(Command("profile-metric renderBeforeXRWait").find("\"samples\":0")!=std::string::npos,"discard boundary from a previous capture epoch");
    Command("profile-stop");
    Check(Command("profile-metric invalid").find("\"ok\":false")!=std::string::npos,"unknown metric");
    std::puts("Frame profile lifecycle, percentile and concurrency checks passed.");
}
